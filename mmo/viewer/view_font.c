#define GLYPH_N ((int)(sizeof GLYPHS / sizeof GLYPHS[0]))

/* Unknown characters are a filled box rather than a gap: a message with a hole
 * in it looks like a bug in the message, which is exactly what it is. */
static const uint8_t TOFU[OPENMMO_FONT_H] =
    { 0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F };

static const uint8_t *glyph_rows(char c)
{
    int i;

    for (i = 0; i < GLYPH_N; i++)
        if (GLYPHS[i].c == c) return GLYPHS[i].row;
    return TOFU;
}

int openmmo_font_width(const char *text, int scale)
{
    int n = 0;

    if (text == NULL || scale < 1) return 0;
    while (*text++ != '\0') n++;
    if (n == 0) return 0;
    return (n * (OPENMMO_FONT_W + 1) - 1) * scale;
}

void openmmo_font_draw(uint32_t *px, int w, int h, int x, int y,
                       const char *text, int scale, uint32_t colour)
{
    int i;

    if (px == NULL || text == NULL || scale < 1) return;
    for (i = 0; text[i] != '\0'; i++) {
        const uint8_t *rows = glyph_rows(text[i]);
        int gx = x + i * (OPENMMO_FONT_W + 1) * scale;
        int row, col, sy, sx;

        for (row = 0; row < OPENMMO_FONT_H; row++) {
            for (col = 0; col < OPENMMO_FONT_W; col++) {
                if ((rows[row] & (1u << (OPENMMO_FONT_W - 1 - col))) == 0)
                    continue;
                for (sy = 0; sy < scale; sy++) {
                    int py = y + row * scale + sy;

                    if (py < 0 || py >= h) continue;
                    for (sx = 0; sx < scale; sx++) {
                        int pxx = gx + col * scale + sx;

                        if (pxx < 0 || pxx >= w) continue;
                        px[(size_t)py * w + pxx] = colour;
                    }
                }
            }
        }
    }
}

void openmmo_font_draw_centred(uint32_t *px, int w, int h, int cx, int y,
                               const char *text, int scale, uint32_t colour)
{
    openmmo_font_draw(px, w, h, cx - openmmo_font_width(text, scale) / 2, y,
                      text, scale, colour);
}
